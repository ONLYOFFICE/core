static const size_t BRUSH_COLOR_OFFSET    = 92;
static const size_t PLACEABLE_HEADER_SIZE = 22;

inline std::wstring GenerateHrWmfHex(unsigned char r, unsigned char g, unsigned char b)
{
	const size_t unSize = sizeof(wmf_hr);

	unsigned char arBuffer[sizeof(wmf_hr)];
	std::memcpy(arBuffer, wmf_hr, unSize);

	arBuffer[BRUSH_COLOR_OFFSET + 0] = r;
	arBuffer[BRUSH_COLOR_OFFSET + 1] = g;
	arBuffer[BRUSH_COLOR_OFFSET + 2] = b;

	static const wchar_t pHexDigits[] = L"0123456789abcdef";

	std::wstring sHex;
	sHex.reserve((unSize - PLACEABLE_HEADER_SIZE) * 2);
	for (size_t i = PLACEABLE_HEADER_SIZE; i < unSize; ++i)
	{
		sHex += pHexDigits[(arBuffer[i] >> 4) & 0x0F];
		sHex += pHexDigits[arBuffer[i] & 0x0F];
	}
	return sHex;
}
